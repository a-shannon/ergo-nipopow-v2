//! Production Ergo NiPoPoW V2 parameter profiles and exact integer difficulty-cap grids.
//!
//! Zero floating-point arithmetic: `GRID_513[k] = ceil(2^(k/8))` is precomputed
//! using exact integer 8th-root bounds (`g^8 >= 2^k` and `(g-1)^8 < 2^k`).

use crate::daa::MAX_CAP;

#[derive(Clone, Copy, Debug, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
pub enum ProfileId {
    /// Reserved legacy wire tag retained exclusively for cross-profile isolation tests.
    /// Production certificates and verifiers MUST use `V2Production128` (`id = 3`).
    /// Retained with fixed wire discriminant for deterministic serialization parity.
    V2Production = 1,
    /// Legacy wire tag retained for cross-profile isolation tests only; use `V2Production128`.
    V2LegacyR15 = 2,
    /// End-to-end 128-bit production V2 profile: 2^(1/8) geometric cap grid (513 levels),
    /// L=896 (7 * 128 EIP-37 epochs), s=210 (exact 15/64 = 23.4375% fresh chain-quality ratio),
    /// beta=3/4 (982 draws/scale at Q_A = 2^128 + 1), r_theta=1.35.
    /// Certified in pure exact rational arithmetic (scripts/certify_profiles.py):
    /// eps_rank <= 2^-131.63 (A=151, t=40), eps_early = 2^-130*(1+3.06e-9) <= 2^-129.99, eps_audit <= 2^-130.30,
    /// eps_global_race <= 2^-131.15, eps_local_race <= 2^-131.20, and total analytical
    /// union sum <= 2^-128.35 < 2^-128.
    V2Production128 = 3,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct ProfileParams {
    pub id: ProfileId,
    pub k0: u32,
    pub window_l: u32,
    pub fresh_s: u32,
    /// First modern localized-origin height `s_L = 844_672 + k0 + L`.
    pub modern_origin_start: u32,
    pub draws_per_scale: u32,
    pub legacy_allowance_b1: u128,
    /// Sampled-mode maturities `(v1, early_v2, modern)`.
    pub m_sampled: [u128; 3],
    /// Exact-tail maturities `(v1, early_v2, modern)`.
    pub m_exact: [u128; 3],
    /// Fine geometric grid (`GRID_513`) vs power-of-2 grid (`65` levels).
    pub use_fine_grid: bool,
}

impl ProfileId {
    pub const fn params(self) -> ProfileParams {
        match self {
            Self::V2Production => ProfileParams {
                id: Self::V2Production,
                k0: 64,
                window_l: 768,
                fresh_s: 180,
                modern_origin_start: 844_672 + 64 + 768, // 845_504
                draws_per_scale: 617,
                legacy_allowance_b1: 9_072,
                // +1 safety margin above exact ceiling for all 6 maturities (b1 = 9_072)
                m_sampled: [39_807, 21_476, 3_585],
                m_exact: [19_734, 10_662, 1_808],
                use_fine_grid: true,
            },
            Self::V2LegacyR15 => ProfileParams {
                id: Self::V2LegacyR15,
                k0: 64,
                window_l: 1024,
                fresh_s: 240,
                modern_origin_start: 844_672 + 64 + 1024, // 845_760
                draws_per_scale: 466,
                legacy_allowance_b1: 8_319,
                m_sampled: [43_410, 23_155, 4_995],
                m_exact: [17_867, 9_548, 2_090],
                use_fine_grid: false,
            },
            Self::V2Production128 => ProfileParams {
                id: Self::V2Production128,
                k0: 64,
                window_l: 896,
                fresh_s: 210,
                modern_origin_start: 844_672 + 64 + 896, // 845_632
                draws_per_scale: 982,
                legacy_allowance_b1: 9_072,
                // +1 safety margin above exact rational ceiling [40_098, 21_768, 4_141] / [19_878, 10_806, 2_082]
                m_sampled: [40_099, 21_769, 4_142],
                m_exact: [19_879, 10_807, 2_083],
                use_fine_grid: true,
            },
        }
    }
}

impl ProfileParams {
    /// Exact monotonic integer ceiling onto the profile cap grid.
    pub fn grid_ceil(&self, value: u128) -> Option<u128> {
        if value == 0 {
            return Some(1);
        }
        if value > MAX_CAP {
            return None;
        }
        if !self.use_fine_grid {
            return Some(value.next_power_of_two());
        }
        let idx = GRID_513.partition_point(|&g| g < value);
        GRID_513.get(idx).copied()
    }

    /// Modern localized cap `gridceil(floor(3 * d / 2))`.
    pub fn modern_cap(&self, max_diff: u128) -> Option<u128> {
        if max_diff == 0 || max_diff > MAX_CAP {
            return None;
        }
        let bound = max_diff.checked_add(max_diff / 2)?;
        self.grid_ceil(bound)
    }

    /// Origin zone index: 0 = v1 (`1..=417_791`), 1 = early v2 (`417_792..s_L`), 2 = modern (`>= s_L`).
    pub const fn origin_zone(&self, height: u32) -> usize {
        if height <= crate::header::AUTOLYKOS_V1_LAST_HEIGHT {
            0
        } else if height < self.modern_origin_start {
            1
        } else {
            2
        }
    }
}

